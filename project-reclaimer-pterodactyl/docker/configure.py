#!/usr/bin/env python3
"""Generate or patch dedicated.toml for Pterodactyl.

Design goal: never require a full TOML parser/writer dependency. Almost
every Project Reclaimer setting has an official RECLAIMER_DEDICATED_*
environment variable override (see Project Reclaimer hosting docs, section
"Environment variables"), so this script only ever needs to manage the two
fields that have NO environment override: a server's `name` and `port`
(plus, optionally, which content it plays, since map/game has no env
override either). Everything else is left to the admin or to environment
variables, applied by entrypoint.sh before this script runs.

To stay safe against corrupting hand-edited files (custom playlists, admin
lists, bans, [rcon]/[master] tuning), this script only ever rewrites the
text between two sentinel comment lines. The rest of dedicated.toml,
including anything upstream's own "dedicated init" or the admin added, is
left completely untouched.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

SENTINEL_START = "# >>> PTERODACTYL MANAGED SERVER BLOCK (generated by configure.py; edits here are overwritten on every start) >>>"
SENTINEL_END = "# <<< PTERODACTYL MANAGED SERVER BLOCK <<<"

DEFAULT_TEMPLATE = """# dedicated.toml
#
# This file is managed in part by the Pterodactyl egg for Project
# Reclaimer. Only the block between the PTERODACTYL MANAGED SERVER BLOCK
# markers below is regenerated automatically on every container start;
# everything else (admins, playlists, [rcon], [master] tuning, etc.) is
# yours to edit and will be preserved across restarts.
#
# Most general settings are supplied via RECLAIMER_DEDICATED_* environment
# variables from the egg's Pterodactyl variables instead of being written
# here directly. See CONFIGURATION.md for the full list.

game = "game"
content = "content"
data = "data"
bans = "bans.json"
public_address = ""
upnp = false
auto_update = false
host_name = ""
admins = []

[master]
enabled = true
port = 49175

[rcon]
password = ""
address = "127.0.0.1"

[defaults]

{sentinel_block}
"""


def toml_string(value: str) -> str:
    """Render a Python string as a double-quoted TOML basic string."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    escaped = escaped.replace("\n", "\\n").replace("\t", "\\t")
    return f'"{escaped}"'


def render_server_block(env: dict) -> str:
    name = (env.get("SERVER_NAME") or "Project Reclaimer Server").strip()[:48]
    if not name:
        name = "Project Reclaimer Server"

    port_raw = env.get("SERVER_PORT") or env.get("SERVER_ALLOCATION_PORT") or ""
    try:
        port = int(port_raw)
        if not (1024 <= port <= 65535):
            raise ValueError
    except ValueError:
        print(
            f"configure.py: SERVER_PORT='{port_raw}' is not a valid port; "
            "refusing to generate dedicated.toml with an invalid port.",
            file=sys.stderr,
        )
        sys.exit(1)

    lines = [SENTINEL_START, "[[server]]", f"name = {toml_string(name)}", f"port = {port}"]

    playlist = (env.get("PLAYLIST") or "").strip()
    map_name = (env.get("MAP") or "").strip()
    game_type = (env.get("GAME_TYPE") or "").strip()

    if playlist:
        lines.append(f"playlist = {toml_string(playlist)}")
    elif map_name and game_type:
        lines.append(f"map = {toml_string(map_name)}")
        lines.append(f"game = {toml_string(game_type)}")
    # else: leave unset entirely; upstream defaults to Slayer on Guardian,
    # or to RECLAIMER_DEDICATED_PLAYLIST / _VARIANT if the admin set those
    # as [defaults] overrides, since this server sets none of its own.

    lines.append(SENTINEL_END)
    return "\n".join(lines)


def patch_existing(text: str, block: str) -> tuple[str, bool]:
    start = text.find(SENTINEL_START)
    end = text.find(SENTINEL_END)
    if start == -1 or end == -1 or end < start:
        # No existing managed block (or it was removed/corrupted): append
        # a fresh one rather than touching anything else in the file.
        separator = "\n" if text.endswith("\n") else "\n\n"
        return text + separator + block + "\n", True

    end += len(SENTINEL_END)
    return text[:start] + block + text[end:], False


def main() -> int:
    server_dir = Path(os.environ.get("RECLAIMER_SERVER_DIR", "/home/container/server"))
    server_dir.mkdir(parents=True, exist_ok=True)
    toml_path = server_dir / "dedicated.toml"

    block = render_server_block(os.environ)

    if not toml_path.exists():
        content = DEFAULT_TEMPLATE.format(sentinel_block=block)
        toml_path.write_text(content, encoding="utf-8")
        print(f"configure.py: wrote new {toml_path}")
        return 0

    original = toml_path.read_text(encoding="utf-8")
    updated, appended = patch_existing(original, block)

    if updated == original:
        print(f"configure.py: {toml_path} already up to date")
        return 0

    toml_path.write_text(updated, encoding="utf-8")
    if appended:
        print(
            f"configure.py: managed block missing from {toml_path}; appended "
            "a fresh one without touching the rest of the file"
        )
    else:
        print(f"configure.py: updated managed block in {toml_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
